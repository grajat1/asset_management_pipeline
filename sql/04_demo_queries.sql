-- 1. Run history and operational status
SELECT RUN_ID, BUSINESS_DATE, STATUS, RECEIVED_COUNT, ACCEPTED_COUNT,
       REJECTED_COUNT, DUPLICATE_COUNT, STARTED_AT, COMPLETED_AT,
       ELAPSED_SECONDS, ERROR_MESSAGE
FROM PIPELINE_RUNS
ORDER BY RUN_ID DESC;

-- 2. Curated portfolio positions
SELECT RUN_ID, BUSINESS_DATE, PORTFOLIO_ID, SECURITY_ID, QUANTITY,
       MARKET_PRICE, MARKET_VALUE, PRICE_DATE, CURRENCY,
       SOURCE_POSITION_DATE
FROM GOLD_PORTFOLIO_POSITIONS
ORDER BY RUN_ID, PORTFOLIO_ID, SECURITY_ID;

-- 3. Missing/stale-price and other data-quality exceptions
SELECT *
FROM GOLD_DATA_QUALITY_EXCEPTIONS
ORDER BY RUN_ID, PORTFOLIO_ID, SECURITY_ID;

-- 4. Restricted-security trade exceptions
SELECT *
FROM GOLD_COMPLIANCE_EXCEPTIONS
ORDER BY RUN_ID, TRADE_DATE, TRANSACTION_ID;

-- 5. Rejected transactions
SELECT *
FROM TRANSACTION_REJECTS
ORDER BY RUN_ID, SOURCE_FILE, SOURCE_ROW_NUMBER;

-- 6. Raw transaction volume and distinct IDs
SELECT RUN_ID, COUNT(*) AS RECEIVED_ROWS,
       COUNT(DISTINCT TRANSACTION_ID) AS DISTINCT_TRANSACTION_IDS
FROM TRANSACTIONS_RAW
GROUP BY RUN_ID
ORDER BY RUN_ID;

-- 7. Compare curated value with quantity x price
SELECT *
FROM GOLD_PORTFOLIO_POSITIONS
WHERE ABS(MARKET_VALUE - ROUND(QUANTITY * MARKET_PRICE, 2)) > 0.01;


-- 8. Reconciliation by source dataset
SELECT RUN_ID, DATASET_NAME, RECEIVED_COUNT, ACCEPTED_COUNT,
       REJECTED_COUNT, DUPLICATE_COUNT, DEFERRED_COUNT
FROM PIPELINE_RECONCILIATION
ORDER BY RUN_ID, DATASET_NAME;

-- 9. Published run pointer (consumers should use this RUN_ID)
SELECT BUSINESS_DATE, RUN_ID, PUBLISHED_AT
FROM GOLD_PUBLISHED_RUNS
ORDER BY BUSINESS_DATE DESC;

-- 10. Transaction version history and current/superseded status
SELECT TRANSACTION_ID, RECORD_VERSION, VERSION_STATUS, SUPERSEDES_VERSION,
       CORRECTION_REASON, QUANTITY, TRADE_DATE, ACCEPTED_AT
FROM TRANSACTIONS
ORDER BY TRANSACTION_ID, RECORD_VERSION;


-- 11. Reference-data rows quarantined before curated merges
SELECT RUN_ID, DATASET_NAME, SOURCE_FILE, SOURCE_ROW_NUMBER, NATURAL_KEY, REASON, DETAILS, REJECTED_AT
FROM REFERENCE_DATA_REJECTS
ORDER BY RUN_ID, DATASET_NAME, SOURCE_ROW_NUMBER;

-- 12. Delivery attempt history (including duplicate skips and forced replays)
SELECT RUN_ID, FILE_HASH, ATTEMPT_STATUS, STARTED_AT, COMPLETED_AT
FROM FILE_DELIVERY_ATTEMPTS
ORDER BY RUN_ID DESC;