-- Silver: accepted canonical transactions and explicit rejects.
CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID VARCHAR2(30) NOT NULL,
    PORTFOLIO_ID VARCHAR2(20) NOT NULL,
    SECURITY_ID VARCHAR2(20) NOT NULL,
    TRADE_DATE DATE NOT NULL,
    QUANTITY NUMBER(18,4) NOT NULL,
    PRICE NUMBER(18,6) NOT NULL,
    CURRENCY VARCHAR2(3) NOT NULL,
    SOURCE_FILE VARCHAR2(200) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER NOT NULL,
    RUN_ID NUMBER NOT NULL,
    RECORD_HASH VARCHAR2(64) NOT NULL,
    RECORD_VERSION NUMBER(10,0) DEFAULT 1 NOT NULL,
    VERSION_STATUS VARCHAR2(20) DEFAULT 'CURRENT' NOT NULL,
    SUPERSEDES_VERSION NUMBER(10,0),
    CORRECTION_REASON VARCHAR2(500),
    ACCEPTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (TRANSACTION_ID, RECORD_VERSION),
    CONSTRAINT CK_TX_VERSION_STATUS CHECK (VERSION_STATUS IN ('CURRENT', 'SUPERSEDED')),
    CONSTRAINT CK_TX_VERSION_POSITIVE CHECK (RECORD_VERSION >= 1),
    CONSTRAINT CK_TX_QUANTITY_NONZERO CHECK (QUANTITY <> 0),
    CONSTRAINT CK_TX_PRICE_POSITIVE CHECK (PRICE > 0),
    CONSTRAINT CK_TX_CORRECTION_METADATA CHECK (
      (RECORD_VERSION = 1 AND SUPERSEDES_VERSION IS NULL) OR
      (RECORD_VERSION > 1 AND SUPERSEDES_VERSION = RECORD_VERSION - 1
       AND CORRECTION_REASON IS NOT NULL)
    )
);

CREATE UNIQUE INDEX UQ_TX_CURRENT_VERSION ON TRANSACTIONS (
    CASE WHEN VERSION_STATUS = 'CURRENT' THEN TRANSACTION_ID END
);

