-- Run as a dedicated schema owner. This script is not idempotent:
-- drop/recreate only in a disposable assessment schema if rerunning it.
CREATE TABLE SECURITY_MASTER (
    SECURITY_MASTER_KEY NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SECURITY_ID VARCHAR2(20) NOT NULL,
    ISIN VARCHAR2(20),
    ASSET_CLASS VARCHAR2(30),
    CURRENCY VARCHAR2(3) NOT NULL,
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE,
    CONSTRAINT UQ_SECURITY_MASTER_VERSION UNIQUE (SECURITY_ID, EFFECTIVE_FROM),
    CONSTRAINT CK_SECURITY_MASTER_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM)
);

CREATE TABLE POSITIONS (
    PORTFOLIO_ID VARCHAR2(20) NOT NULL,
    SECURITY_ID VARCHAR2(20) NOT NULL,
    POSITION_DATE DATE NOT NULL,
    QUANTITY NUMBER(18,4) NOT NULL,
    BOOK_VALUE NUMBER(18,2) NOT NULL,
    CURRENCY VARCHAR2(3) NOT NULL,
    CONSTRAINT PK_POSITIONS PRIMARY KEY (PORTFOLIO_ID, SECURITY_ID, POSITION_DATE)
);

CREATE TABLE MARKET_PRICES (
    SECURITY_ID VARCHAR2(20) NOT NULL,
    PRICE_DATE DATE NOT NULL,
    PRICE NUMBER(18,6) NOT NULL,
    PRICE_CURRENCY VARCHAR2(3) NOT NULL,
    PRICE_SOURCE VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_MARKET_PRICES PRIMARY KEY (SECURITY_ID, PRICE_DATE, PRICE_SOURCE),
    CONSTRAINT CK_MARKET_PRICE_POSITIVE CHECK (PRICE > 0)
);

CREATE TABLE RESTRICTED_SECURITIES (
    SECURITY_ID VARCHAR2(20) NOT NULL,
    RESTRICTION_TYPE VARCHAR2(30) NOT NULL,
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE,
    STATUS VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_RESTRICTED PRIMARY KEY
      (SECURITY_ID, RESTRICTION_TYPE, EFFECTIVE_FROM),
    CONSTRAINT CK_RESTRICTED_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM)
);

CREATE TABLE PIPELINE_RUNS (
    RUN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BUSINESS_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    STARTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    RECEIVED_COUNT NUMBER DEFAULT 0 NOT NULL,
    ACCEPTED_COUNT NUMBER DEFAULT 0 NOT NULL,
    REJECTED_COUNT NUMBER DEFAULT 0 NOT NULL,
    DUPLICATE_COUNT NUMBER DEFAULT 0 NOT NULL,
    ERROR_MESSAGE VARCHAR2(1000),
    ELAPSED_SECONDS NUMBER,
    CONSTRAINT CK_PIPELINE_RUN_STATUS CHECK
      (STATUS IN ('RUNNING', 'LOADED', 'SUCCEEDED', 'FAILED', 'SKIPPED_DUPLICATE'))
);

-- Consumers must resolve the latest complete run through this table.
-- The pointer is updated in the same transaction as the successful run status.
CREATE TABLE GOLD_PUBLISHED_RUNS (
    BUSINESS_DATE DATE PRIMARY KEY,
    RUN_ID NUMBER NOT NULL,
    PUBLISHED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_PUBLISHED_RUN FOREIGN KEY (RUN_ID) REFERENCES PIPELINE_RUNS(RUN_ID)
);

CREATE TABLE FILE_DELIVERIES (
    FILE_HASH VARCHAR2(64) PRIMARY KEY,
    FILE_NAME VARCHAR2(200) NOT NULL,
    RUN_ID NUMBER NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    RECEIVED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    CONSTRAINT FK_DELIVERY_RUN FOREIGN KEY (RUN_ID)
      REFERENCES PIPELINE_RUNS(RUN_ID),
    CONSTRAINT CK_FILE_DELIVERY_STATUS CHECK (STATUS IN ('PROCESSING', 'SUCCEEDED', 'FAILED'))
);

-- Retains every attempt, including forced replays, for delivery-level auditability.
CREATE TABLE FILE_DELIVERY_ATTEMPTS (
    RUN_ID NUMBER PRIMARY KEY,
    FILE_HASH VARCHAR2(64) NOT NULL,
    ATTEMPT_STATUS VARCHAR2(30) NOT NULL,
    STARTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    CONSTRAINT FK_DELIVERY_ATTEMPT_RUN FOREIGN KEY (RUN_ID) REFERENCES PIPELINE_RUNS(RUN_ID),
    CONSTRAINT FK_DELIVERY_ATTEMPT_HASH FOREIGN KEY (FILE_HASH) REFERENCES FILE_DELIVERIES(FILE_HASH),
    CONSTRAINT CK_DELIVERY_ATTEMPT_STATUS CHECK
      (ATTEMPT_STATUS IN ('PROCESSING', 'SUCCEEDED', 'FAILED', 'SKIPPED_DUPLICATE'))
);

